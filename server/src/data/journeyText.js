export function journeyText(lang) {
  const texts = JOURNEY_TEXT[lang] ?? JOURNEY_TEXT.fr;
  const fill = (key, vars = {}) => String(texts[key] ?? JOURNEY_TEXT.fr[key]).replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m);
  fill.advice = (id) => texts.advice[id] ?? JOURNEY_TEXT.fr.advice[id];
  return fill;
}
